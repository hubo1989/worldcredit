// scripts/import-to-d1.mjs
// Read exported JSON files and generate SQL INSERT statements for D1 (SQLite).
// Usage: npx wrangler d1 execute worldcredit --local --file=data/import.sql

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { execSync } from 'child_process'

const __dirname = dirname(fileURLToPath(import.meta.url))
const EXPORT_DIR = join(__dirname, '..', 'data', 'insforge-export')
const OUT_FILE = join(EXPORT_DIR, '..', 'import.sql')

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL'
  if (typeof str === 'boolean') return str ? '1' : '0'
  if (typeof str === 'number') return String(str)
  if (typeof str === 'object') return `'${JSON.stringify(str).replace(/'/g, "''")}'`
  return `'${String(str).replace(/'/g, "''")}'`
}

// Column type mappings: InsForge Postgres → D1 SQLite
// UUID → TEXT, TIMESTAMPTZ → TEXT, BOOLEAN → INTEGER, NUMERIC → REAL, JSONB → TEXT
function transformValue(key, value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'boolean') return value ? '1' : '0'
  if (typeof value === 'object') return escapeSql(JSON.stringify(value))
  return escapeSql(value)
}

const TABLES = [
  'users', 'banks', 'card_products', 'benefits', 'promos',
  'card_holders', 'credit_cards', 'bills', 'bill_items', 'payments',
  'benefit_usages', 'promo_usages', 'system_settings',
  'push_subscriptions', 'reminder_logs',
  'bill_email_sources', 'record_attachments', 'email_parse_logs',
  'user_preferences', 'gmail_ledger_entries', 'bill_import_drafts',
  'notification_preferences', 'notification_history',
]

function importTable(table) {
  const filePath = join(EXPORT_DIR, `${table}.json`)
  if (!existsSync(filePath)) {
    console.log(`[import] ${table}: no export file, skipping`)
    return []
  }
  const rows = JSON.parse(readFileSync(filePath, 'utf-8'))
  if (!Array.isArray(rows) || rows.length === 0) {
    console.log(`[import] ${table}: 0 rows`)
    return []
  }
  const statements = []
  // Get column names from first row, normalize boolean → integer, object → JSON string
  const cols = Object.keys(rows[0])
  for (const row of rows) {
    // Fill missing columns with NULL
    const values = cols.map(col => transformValue(col, row[col]))
    statements.push(
      `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${values.join(', ')});`
    )
  }
  console.log(`[import] ${table}: ${rows.length} rows, ${statements.length} statements`)
  return statements
}

function main() {
  mkdirSync(dirname(OUT_FILE), { recursive: true })
  const allStatements = ['-- WorldCredit D1 import script (generated)', '-- Generated by scripts/import-to-d1.mjs', '']

  for (const table of TABLES) {
    try {
      allStatements.push(...importTable(table))
      allStatements.push('')
    } catch (err) {
      console.error(`[import] ${table}: ${err.message}`)
    }
  }

  writeFileSync(OUT_FILE, allStatements.join('\n'))
  console.log(`\nWritten to ${OUT_FILE}`)
  console.log(`Run: npx wrangler d1 execute worldcredit --local --file=${OUT_FILE}`)
}

main()
